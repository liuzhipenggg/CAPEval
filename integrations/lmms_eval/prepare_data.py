"""Generate local inference JSONL for lmms-eval / custom loaders.

Usage:
  python -m integrations.lmms_eval.prepare_data
  # or
  CAPEVAL_HOME=/path/to/CAPEval python integrations/lmms_eval/prepare_data.py
"""

from __future__ import annotations

import sys
from pathlib import Path

_HERE = Path(__file__).resolve().parent
_ROOT = _HERE.parents[1]
if str(_ROOT) not in sys.path:
    sys.path.insert(0, str(_ROOT))

from capeval.api import export_inference_jsonl, export_vlmeval_tsv


def main() -> int:
    out_jsonl = (_HERE / "data" / "capeval_infer.jsonl").resolve()
    out_tsv = (_ROOT / "integrations" / "exports" / "capeval_vlmeval.tsv").resolve()
    p1 = export_inference_jsonl(out_jsonl)
    p2 = export_vlmeval_tsv(out_tsv)

    # Machine-local yaml with absolute data_files (gitignored).
    local_yaml = _HERE / "capeval_local.yaml"
    local_yaml.write_text(
        f"""# Auto-generated by prepare_data.py — do not commit.
task: "capeval"
dataset_path: json
dataset_kwargs:
  data_files:
    test: {out_jsonl}
test_split: test
output_type: generate_until
doc_to_visual: !function utils.capeval_doc_to_visual
doc_to_text: !function utils.capeval_doc_to_text
doc_to_messages: !function utils.capeval_doc_to_messages
generation_kwargs:
  max_new_tokens: 1024
  temperature: 0.0
process_results: !function utils.capeval_process_results
metric_list:
  - metric: capeval_c
    aggregation: !function utils.capeval_aggregate_c
    higher_is_better: true
  - metric: capeval_p
    aggregation: !function utils.capeval_aggregate_p
    higher_is_better: true
metadata:
  version: 0.1
""",
        encoding="utf-8",
    )

    print(f"Wrote {p1}")
    print(f"Wrote {p2}")
    print(f"Wrote {local_yaml}")
    print(f"Images remain under {_ROOT / 'data' / 'image'}")
    print("lmms-eval: prefer --tasks capeval with include_path=integrations/lmms_eval")
    print("  (use capeval_local.yaml via copying over capeval.yaml if relative paths fail)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
